// ---------------------------------------------------------------------------
// Splicing
// ---------------------------------------------------------------------------

/**
 * Line ending of the host file. The repo has core.autocrlf=true, so a checked
 * out client.js is CRLF on Windows and LF elsewhere; a generated region that
 * hard-codes one of them disagrees with the rest of the file on the other
 * platform (and makes every generator's --check fail there).
 */
function detectEol(text) {
  const crlf = (text.match(/\r\n/g) || []).length;
  const lf = (text.match(/\n/g) || []).length;
  return lf > 0 && crlf * 2 >= lf ? "\r\n" : "\n";
}

/** Indent the renderer to factory depth, in the host file's line ending. */
function buildBlock(eol) {
  const body = RENDERER_SOURCE.split("\n").map((line) => (line ? "\t\t" + line : ""));
  return body.join(eol);
}

/**
 * The generator and its output both live inside template-literal-heavy files:
 * a stray backtick or `${` in the renderer would break whichever template it
 * lands in. Fail loudly instead of shipping a broken bundle.
 */
function assertSpliceSafe(block) {
  const forbidden = [String.fromCharCode(96), "${"];
  for (const token of forbidden) {
    if (block.includes(token)) {
      console.error(`generate-markdown: generated block contains ${JSON.stringify(token)} — it would break a template literal`);
      process.exit(1);
    }
  }
}

/**
 * Replace the existing MARKDOWN region, or bootstrap it below the icon block
 * when the markers are not in the file yet.
 */
function splice(source, block, eol) {
  const startIndex = source.indexOf(START);
  const endIndex = source.indexOf(END);
  if (startIndex !== -1 && endIndex > startIndex) {
    const lineStart = source.lastIndexOf("\n", startIndex) + 1;
    return source.slice(0, lineStart) + block + source.slice(endIndex + END.length);
  }
  if (startIndex !== -1 || endIndex !== -1) return null; // half a marker pair
  const iconsEnd = source.indexOf(ICONS_END);
  if (iconsEnd === -1) return null;
  const lineEnd = source.indexOf("\n", iconsEnd);
  if (lineEnd === -1) return null;
  // Directly below /* ICONS:END */, so both generated blocks sit together at
  // the top of the factory where react is already in scope.
  return source.slice(0, lineEnd + 1) + block + eol + source.slice(lineEnd + 1);
}

const source = readFileSync(clientPath, "utf-8");
const eol = detectEol(source);
const block = buildBlock(eol);
assertSpliceSafe(block);
const next = splice(source, block, eol);
if (next === null) {
  console.error("generate-markdown: cannot locate the MARKDOWN region in lib/client.js");
  console.error(`  expected "${START} ..." / "${END}", or an "${ICONS_END}" line to insert after`);
  process.exit(1);
}
const lines = block.split(eol).length;

if (process.argv.includes("--check")) {
  if (next === source) {
    console.log(`generate-markdown: up to date (${lines} lines)`);
    process.exit(0);
  }
  console.error("generate-markdown: lib/client.js is STALE — run `node app/plugins/dsh-product-shell/scripts/generate-markdown.mjs`");
  process.exit(1);
}

if (next === source) {
  console.log(`generate-markdown: no change (${lines} lines)`);
  process.exit(0);
}
writeFileSync(clientPath, next);
console.log(`generate-markdown: wrote ${lines} lines into lib/client.js`);
